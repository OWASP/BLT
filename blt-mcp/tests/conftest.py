import pytest
import subprocess
import shutil
import sys
import os
from pathlib import Path
from dotenv import load_dotenv


def pytest_sessionfinish(session, exitstatus):
    """
    Automatically runs mcp-vcr verify after all pytest tests pass.
    """
    if exitstatus == 0:
        # Load .env file from project root
        root_dir = Path(__file__).parent.parent
        load_dotenv(dotenv_path=root_dir / ".env")

        if not os.getenv("BLT_API_KEY"):
            print(
                "\n=== Skipping Golden Snapshot Verification: BLT_API_KEY not set ==="
            )
            return

        snapshots_dir = Path("snapshots")
        if snapshots_dir.exists() and any(snapshots_dir.glob("*.yaml")):
            # Clean up replay artifacts generated by previous runs before verifying,
            # so they don't get picked up as golden snapshots.
            for replay_file in snapshots_dir.glob("*-replay-*.yaml"):
                replay_file.unlink(missing_ok=True)

            print("\n=== Running Golden Snapshot Verification ===")
            mcp_vcr_bin = shutil.which("mcp-vcr")
            if mcp_vcr_bin is None:
                print(
                    "WARNING: mcp-vcr not found on PATH. Skipping snapshot verification."
                )
                return
            cmd = [
                str(mcp_vcr_bin),
                "verify",
                str(snapshots_dir),
                "--",
                "uv",
                "run",
                "-m",
                "blt_mcp.server",
            ]
            result = subprocess.run(cmd, capture_output=True, text=True)
            print(result.stdout)
            if result.returncode != 0:
                print(
                    f"ERROR: Golden snapshots verification failed:\n{result.stderr}",
                    file=sys.stderr,
                )
                session.exitstatus = result.returncode
        else:
            print(
                "\n=== No Golden Snapshots found. Run `mcp-vcr record` to create some! ==="
            )
