"""
Pytest Test Hooks and Setup Configurations for BLT-MCP.

This module defines test session hooks that run before/after tests are executed by the pytest framework.

Key Functions:
- `pytest_sessionfinish(session, exitstatus)`: Executed automatically on test completion.
  If all test suites pass (`exitstatus == 0`), it looks for golden session recordings under the `snapshots/` folder.
  If found, it cleans up previous temporary replays, spawns the local FastMCP server in a subprocess (`uv run -m blt_mcp.server`),
  and runs the `mcp-vcr verify` verification tool to match actual network exchanges against the golden snapshots.

Dependencies:
- `pytest`, `subprocess`, `shutil`, `sys`, `os`, `pathlib`, `dotenv.load_dotenv`
"""

import os
import shutil
import subprocess
import sys
from pathlib import Path

import pytest
from dotenv import load_dotenv

# Enable HTTP mock layer globally for all test server subprocesses
os.environ["BLT_MOCK_HTTP"] = "true"


@pytest.fixture(autouse=True)
def clean_env():
    # Isolate tests from local development environment overrides
    orig_base = os.environ.get("BLT_API_BASE")
    orig_key = os.environ.get("BLT_API_KEY")
    orig_token = os.environ.get("BLT_MCP_TOKEN")

    os.environ.pop("BLT_API_BASE", None)
    os.environ.pop("BLT_API_KEY", None)
    os.environ.pop("BLT_MCP_TOKEN", None)

    yield

    for name, value in (
        ("BLT_API_BASE", orig_base),
        ("BLT_API_KEY", orig_key),
        ("BLT_MCP_TOKEN", orig_token),
    ):
        if value is None:
            os.environ.pop(name, None)
        else:
            os.environ[name] = value


def pytest_sessionfinish(session, exitstatus):
    """
    Automatically runs mcp-vcr verify after all pytest tests pass.
    """
    if exitstatus == 0:
        # Load .env file from project root
        root_dir = Path(__file__).parent.parent
        load_dotenv(dotenv_path=root_dir / ".env")

        # Snapshot verification replays requests against the live API, so
        # results are non-deterministic. Only run when explicitly opted in.
        verify_env = os.getenv("BLT_VERIFY_SNAPSHOTS", "false").lower()
        if verify_env not in ("true", "1", "yes"):
            return

        if not os.getenv("BLT_API_KEY"):
            print(
                "\n=== Skipping Golden Snapshot Verification: BLT_API_KEY not set ==="
            )
            return

        snapshots_dir = Path("snapshots")
        if snapshots_dir.exists() and any(snapshots_dir.glob("*.yaml")):
            # Clean up replay artifacts generated by previous runs before verifying,
            # so they don't get picked up as golden snapshots.
            for replay_file in snapshots_dir.glob("*-replay-*.yaml"):
                replay_file.unlink(missing_ok=True)

            print("\n=== Running Golden Snapshot Verification ===")
            mcp_vcr_bin = shutil.which("mcp-vcr")
            if mcp_vcr_bin is None:
                print(
                    "WARNING: mcp-vcr not found on PATH. Skipping snapshot verification."
                )
                return
            cmd = [
                str(mcp_vcr_bin),
                "verify",
                str(snapshots_dir),
                "--",
                "uv",
                "run",
                "--no-sync",
                "-m",
                "blt_mcp.server",
            ]
            try:
                result = subprocess.run(
                    cmd,
                    env=os.environ.copy(),
                    capture_output=True,
                    text=True,
                    check=False,
                    timeout=120,
                )
                print(result.stdout)
                if result.returncode != 0:
                    print(
                        f"ERROR: Golden snapshots verification failed:\n{result.stderr}",
                        file=sys.stderr,
                    )
                    session.exitstatus = result.returncode
            except subprocess.TimeoutExpired:
                print(
                    "ERROR: Golden snapshot verification timed out after 120 seconds.",
                    file=sys.stderr,
                )
                session.exitstatus = 1
        else:
            print(
                "\n=== No Golden Snapshots found. Run `mcp-vcr record` to create some! ==="
            )
